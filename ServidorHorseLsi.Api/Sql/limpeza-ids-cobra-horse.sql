-- Limpa IDs gravados pelo replicador no Click (SQL Server / lsidemo).
-- Nao apaga clientes/contratos/parcelas/planos — so zera o vinculo com o Cobra.
-- Rode DEPOIS de limpar o Cobra (limpeza-replicacao-teste-pgsql.sql).

UPDATE dbo.CLIENTE SET ID_ORIGINAL_STRING = NULL WHERE ID_ORIGINAL_STRING IS NOT NULL;
UPDATE dbo.TIPO_CONTRATO SET ID_ORIGINAL = NULL WHERE ID_ORIGINAL IS NOT NULL;
UPDATE dbo.CONTRATOS SET ID_ORIGINAL = NULL WHERE ID_ORIGINAL IS NOT NULL;
UPDATE dbo.CONTAS_PARCELAS SET ID_ORIGINAL = NULL WHERE ID_ORIGINAL IS NOT NULL;
UPDATE dbo.CONTAS_DETALHE SET ID_ORIGINAL = NULL WHERE ID_ORIGINAL IS NOT NULL;
UPDATE dbo.CONTAS_PAGAMENTO SET ID_ORIGINAL = NULL WHERE ID_ORIGINAL IS NOT NULL;

-- Conferência
SELECT 'CLIENTE' AS tabela, COUNT(*) AS com_vinculo FROM dbo.CLIENTE WHERE ID_ORIGINAL_STRING IS NOT NULL
UNION ALL SELECT 'TIPO_CONTRATO', COUNT(*) FROM dbo.TIPO_CONTRATO WHERE ID_ORIGINAL IS NOT NULL
UNION ALL SELECT 'CONTRATOS', COUNT(*) FROM dbo.CONTRATOS WHERE ID_ORIGINAL IS NOT NULL
UNION ALL SELECT 'CONTAS_DETALHE', COUNT(*) FROM dbo.CONTAS_DETALHE WHERE ID_ORIGINAL IS NOT NULL;
